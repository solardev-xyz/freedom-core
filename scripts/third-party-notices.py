#!/usr/bin/env python3
"""Generates THIRD-PARTY-NOTICES for the freedom-cored binary.

The binary statically links third-party crates whose licenses (MIT,
Apache-2.0, BSD-3-Clause, ...) require their notices to ship with it. This
lists every crate that ends up in freedom-cored on any release target
(normal dependencies only: build scripts and proc-macros don't ship), with
its license expression and the license/notice files from its own source.

    python3 scripts/third-party-notices.py          # rewrite the file
    python3 scripts/third-party-notices.py --check  # CI: fail if stale

Needs the crates' sources: run `cargo fetch --locked` first.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD-PARTY-NOTICES"
BINARY = "freedom-cored"
# Every target the release workflow builds.
TARGETS = [
    "aarch64-apple-darwin",
    "x86_64-apple-darwin",
    "x86_64-unknown-linux-musl",
    "aarch64-unknown-linux-musl",
    "x86_64-pc-windows-msvc",
]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")


def shipped_packages(target):
    meta = json.loads(
        subprocess.check_output(
            [
                "cargo", "metadata", "--locked", "--offline",
                "--format-version", "1", "--filter-platform", target,
            ],
            cwd=ROOT,
        )
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == BINARY)
    seen, stack = set(), [root]
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            # Normal dependencies only: build-dependencies and dev-dependencies
            # don't end up in the binary.
            if not any(kind["kind"] is None for kind in dep["dep_kinds"]):
                continue
            package = packages[dep["pkg"]]
            # Proc-macros run at compile time; their code doesn't ship.
            if any("proc-macro" in t["kind"] for t in package["targets"]):
                continue
            stack.append(dep["pkg"])
    return [packages[i] for i in seen if packages[i]["source"] is not None]


def license_files(package):
    directory = pathlib.Path(package["manifest_path"]).parent
    files = sorted(
        f for f in directory.iterdir()
        if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES)
    )
    if package.get("license_file"):
        named = directory / package["license_file"]
        if named.is_file() and named not in files:
            files.append(named)
    return files


def generate():
    crates = {}
    for target in TARGETS:
        for package in shipped_packages(target):
            crates[(package["name"], package["version"])] = package
    lines = [
        "THIRD-PARTY NOTICES for freedom-cored",
        "",
        "freedom-cored statically links the following third-party crates. Each",
        "is listed with its license expression, followed by the license and",
        "notice texts its source distributes. Generated by",
        "scripts/third-party-notices.py; do not edit.",
        "",
    ]
    texts = {}  # text -> [crate labels]
    for (name, version) in sorted(crates):
        package = crates[(name, version)]
        expression = package.get("license") or "see the license files below"
        lines.append(f"- {name} {version}: {expression}")
        files = license_files(package)
        if not files:
            texts.setdefault(f"(no license file in the {name} {version} source)", []).append(
                f"{name} {version}"
            )
        for file in files:
            text = file.read_text(encoding="utf-8", errors="replace").strip()
            texts.setdefault(text, []).append(f"{name} {version} ({file.name})")
    lines.append("")
    for text, owners in sorted(texts.items(), key=lambda item: item[1][0]):
        lines.append("=" * 72)
        lines.append("Used by: " + ", ".join(owners))
        lines.append("-" * 72)
        lines.append(text)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    content = generate()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("THIRD-PARTY-NOTICES is stale: run python3 scripts/third-party-notices.py",
                  file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
