fn b64(s: &str) -> String {
    STANDARD.encode(s)
}

/// A core with the abandon...about wallet imported (unlocked); next ID 3.
fn unlocked(data: &Path, locks: &Path, env: &[(&str, &str)]) -> Core {
    let mut core = spawn_env("serve", data, locks, &[], env);
    core.hello();
    let imported = core.call(
        2,
        "vault.import",
        json!({ "password_b64": b64("testpass1"), "mnemonic_b64": b64(ABANDON) }),
    );
    assert!(imported["result"].is_object(), "{imported}");
    core
}

fn mode(path: &Path) -> u32 {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(path).unwrap().permissions().mode() & 0o777
    }
    #[cfg(not(unix))]
    {
        let _ = path;
        0o600
    }
}

fn no_leftovers(dir: &Path) {
    for entry in walk(dir) {
        let name = entry.to_string_lossy().into_owned();
        assert!(!name.ends_with(".freedom-new"), "staged file left: {name}");
    }
}

fn walk(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut out = Vec::new();
    if let Ok(entries) = std::fs::read_dir(dir) {
        for entry in entries {
            let path = entry.unwrap().path();
            if path.is_dir() {
                out.extend(walk(&path));
            } else {
                out.push(path);
            }
        }
    }
    out
}

#[test]
fn bee_identity_matches_the_js_files() {
    let (root, data, locks) = dirs();
    let bee = root.path().join("bee-data");
    let mut core = unlocked(&data, &locks, &[]);
    let written = core.call(
        3,
        "nodes.write_identity",
        json!({ "op_id": "op-bee-1", "node": "bee", "data_dir": bee, "api_port": 1733, "p2p_port": 1734 }),
    );
    assert_eq!(
        written["result"],
        json!({ "address": BEE_ADDRESS, "status": "installed" }),
        "{written}"
    );

    // config.yaml: createBeeConfig's template, with a 64-hex password.
    let config = std::fs::read_to_string(bee.join("config.yaml")).unwrap();
    let password = config
        .lines()
        .find_map(|l| l.strip_prefix("password: "))
        .unwrap()
        .to_owned();
    assert_eq!(password.len(), 64);
    assert!(password.bytes().all(|b| b"0123456789abcdef".contains(&b)));
    let expected = format!(
        "# Bee Configuration (generated by identity injection)\n\
         api-addr: 127.0.0.1:1733\n\
         p2p-addr: :1734\n\
         swap-enable: false\n\
         mainnet: true\n\
         full-node: false\n\
         skip-postage-snapshot: true\n\
         resolver-options: https://ethereum.publicnode.com\n\
         storage-incentives-enable: false\n\
         data-dir: {}\n\
         password: {password}\n",
        bee.display()
    );
    assert_eq!(config, expected);

    // keys/swarm.key: an ethers keystore that opens with that password.
    let keystore = std::fs::read_to_string(bee.join("keys/swarm.key")).unwrap();
    let parsed: Value = serde_json::from_str(&keystore).unwrap();
    assert_eq!(parsed["Crypto"]["kdfparams"]["n"], 131072);
    let key = fc_keys::keystore::decrypt(&keystore, &password).unwrap();
    let hex: String = key
        .to_secret_bytes()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    assert_eq!(hex, BEE_KEY);
    assert_eq!(mode(&bee.join("keys/swarm.key")), 0o600);
    assert_eq!(mode(&bee.join("config.yaml")), 0o600);
    no_leftovers(root.path());

    let status = core.call_shell(4, "nodes.op_status", json!({ "op_id": "op-bee-1" }));
    assert_eq!(status["result"], json!({ "status": "installed" }));
    assert!(!data.join("node-identity-journal.json").exists());
}

/// The check integer of an OpenSSH private key file.
fn check_integer(file: &str) -> u32 {
    let body: String = file.lines().filter(|l| !l.starts_with("-----")).collect();
    let blob = STANDARD.decode(body).unwrap();
    let mut at = b"openssh-key-v1\0".len();
    let skip_string = |at: &mut usize| {
        let len = u32::from_be_bytes(blob[*at..*at + 4].try_into().unwrap()) as usize;
        *at += 4 + len;
    };
    for _ in 0..3 {
        skip_string(&mut at); // cipher, kdf, kdf options
    }
    at += 4; // key count
    skip_string(&mut at); // public key blob
    at += 4; // private section length
    u32::from_be_bytes(blob[at..at + 4].try_into().unwrap())
}

#[test]
fn radicle_identity_matches_the_js_files_and_keeps_the_config() {
    let (root, data, locks) = dirs();
    let home = root.path().join("radicle");
    std::fs::create_dir_all(&home).unwrap();
    std::fs::write(
        home.join("config.json"),
        r#"{"preferredSeeds":["z6Mk@seed.example:8776"],"node":{"alias":"old","listen":[]},"web":{"pinned":{}}}"#,
    )
    .unwrap();
    let mut core = unlocked(&data, &locks, &[]);
    let written = core.call(
        3,
        "nodes.write_identity",
        json!({ "op_id": "op-rad-1", "node": "radicle", "home": home, "alias": "FreedomBrowser" }),
    );
    let result = &written["result"];
    assert_eq!(result["status"], "installed", "{written}");
    assert_eq!(result["did"], RADICLE_DID);
    assert_eq!(
        result["node_id"],
        RADICLE_DID.strip_prefix("did:key:").unwrap()
    );

    assert_eq!(
        std::fs::read_to_string(home.join("keys/radicle.pub")).unwrap(),
        RADICLE_PUB
    );
    // The private key file is exactly fc-keys' (JS-parity) encoding at its
    // own random check integer.
    let private = std::fs::read_to_string(home.join("keys/radicle")).unwrap();
    let mnemonic = fc_keys::Mnemonic::parse(ABANDON).unwrap();
    let keys = fc_keys::freedom::derive_all(&mnemonic.to_seed()).unwrap();
    let expected = fc_keys::openssh::private_key_file_with_check(
        &keys.radicle,
        "FreedomBrowser",
        check_integer(&private),
    );
    assert_eq!(private, expected.as_str());
    assert_eq!(mode(&home.join("keys/radicle")), 0o600);

    // config.json: alias set, everything else kept, JSON.stringify(_, null, 2).
    let config = std::fs::read_to_string(home.join("config.json")).unwrap();
    assert_eq!(
        config,
        "{\n  \"preferredSeeds\": [\n    \"z6Mk@seed.example:8776\"\n  ],\n  \"node\": {\n    \"alias\": \"FreedomBrowser\",\n    \"listen\": []\n  },\n  \"web\": {\n    \"pinned\": {}\n  }\n}"
    );
    no_leftovers(root.path());
}

#[test]
fn writes_need_an_unlocked_vault_and_valid_parameters() {
    let (root, data, locks) = dirs();
    let mut core = unlocked(&data, &locks, &[]);
    let bee = root.path().join("bee");
    let params = |op_id: &str| json!({ "op_id": op_id, "node": "bee", "data_dir": bee, "api_port": 1, "p2p_port": 2 });
    let invalid = [
        params("bad op id!"),
        json!({ "op_id": "a", "node": "bee", "data_dir": "relative/dir", "api_port": 1, "p2p_port": 2 }),
        json!({ "op_id": "a", "node": "bee", "data_dir": bee, "api_port": 0, "p2p_port": 2 }),
        json!({ "op_id": "a", "node": "radicle", "home": bee, "alias": "line\nbreak" }),
        json!({ "op_id": "a", "node": "ipfs" }),
    ];
    for (offset, bad) in invalid.into_iter().enumerate() {
        let reply = core.call(3 + offset as u64, "nodes.write_identity", bad);
        assert_eq!(reply["error"]["code"], "invalid_argument", "{reply}");
    }
    core.call(10, "vault.lock", json!({}));
    let locked = core.call(11, "nodes.write_identity", params("op-1"));
    assert_eq!(locked["error"]["code"], "vault_locked");
    // op_status is main-internal.
    let forbidden = core.call(12, "nodes.op_status", json!({ "op_id": "op-1" }));
    assert_eq!(forbidden["error"]["code"], "forbidden");
    let status = core.call_shell(13, "nodes.op_status", json!({ "op_id": "op-1" }));
    assert_eq!(status["result"]["status"], "not_committed");
    assert!(!bee.exists());
}

#[test]
fn a_lock_before_the_commit_writes_nothing() {
    let (root, data, locks) = dirs();
    let bee = root.path().join("bee");
    let mut core = unlocked(&data, &locks, &[("FREEDOM_CORED_TEST_JOB_DELAY_MS", "800")]);
    let write = request(
        3,
        "nodes.write_identity",
        json!({ "op_id": "op-1", "node": "bee", "data_dir": bee, "api_port": 1, "p2p_port": 2 }),
    );
    core.send_raw(&[frame(&write), frame(&request(4, "vault.lock", json!({})))].concat());
    assert_eq!(core.response(3)["error"]["code"], "vault_locked");
    assert_eq!(core.response(4)["result"], json!({}));
    // Queued behind the abandoned job: it has finished by the time this runs.
    let status = core.call_shell(5, "nodes.op_status", json!({ "op_id": "op-1" }));
    assert_eq!(status["result"]["status"], "not_committed");
    assert!(walk(&bee).is_empty(), "{:?}", walk(&bee));
}

/// Leaves a committed but unfinished Bee journal, as a crash after step 2
/// does: staged files plus the journal, targets still old.
fn interrupted_write(identity: &Path, root: &Path, op_id: &str) {
    std::fs::create_dir_all(root.join("keys")).unwrap();
    std::fs::create_dir_all(identity).unwrap();
    let mut files = Vec::new();
    for (target, contents) in [
        (root.join("keys").join("swarm.key"), "new key"),
        (root.join("config.yaml"), "new config"),
    ] {
        std::fs::write(&target, "old").unwrap();
        let staged = std::path::PathBuf::from(format!("{}.freedom-new", target.display()));
        std::fs::write(&staged, contents).unwrap();
        let digest: String = sha2::Sha256::digest(contents)
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        files.push(json!({ "target": target, "staged": staged, "sha256": digest }));
    }
    let journal = json!({ "op_id": op_id, "node": "bee", "root": root, "files": files });
    std::fs::write(
        identity.join("node-identity-journal.json"),
        journal.to_string(),
    )
    .unwrap();
}

#[test]
fn startup_and_recover_finish_interrupted_writes() {
    let (root, data, locks) = dirs();
    let node = root.path().join("node");
    interrupted_write(&data, &node, "op-crashed");

    // The serve startup rolls it forward before core.hello is answered, and
    // hello reports nothing left to do.
    let mut core = spawn("serve", &data, &locks, &[]);
    let hello = core.hello();
    assert_eq!(hello["result"]["node_recovery"], Value::Null);
    let status = core.call_shell(2, "nodes.op_status", json!({ "op_id": "op-crashed" }));
    assert_eq!(status["result"]["status"], "installed");
    assert_eq!(
        std::fs::read_to_string(node.join("keys/swarm.key")).unwrap(),
        "new key"
    );
    assert_eq!(
        std::fs::read_to_string(node.join("config.yaml")).unwrap(),
        "new config"
    );
    assert!(!data.join("node-identity-journal.json").exists());
    core.close_stdin();
    assert_eq!(core.exit_code(Duration::from_secs(5)), 0);

    // The recover subcommand does the same.
    let other = root.path().join("other");
    interrupted_write(&data, &other, "op-recover");
    let mut recover = spawn("recover", &data, &locks, &[]);
    assert_eq!(recover.line(), "recovered");
    assert_eq!(recover.exit_code(Duration::from_secs(5)), 0);
    assert_eq!(
        std::fs::read_to_string(other.join("config.yaml")).unwrap(),
        "new config"
    );

    // A journal whose staged files are gone is corrupt: recover says so, and
    // a serve startup reports it in core.hello.
    let gone = root.path().join("gone");
    interrupted_write(&data, &gone, "op-gone");
    std::fs::remove_file(gone.join("keys/swarm.key.freedom-new")).unwrap();
    let mut recover = spawn("recover", &data, &locks, &[]);
    assert_eq!(recover.line(), "corrupt op-gone");
    assert_eq!(recover.exit_code(Duration::from_secs(5)), 0);

    let broken = root.path().join("broken");
    interrupted_write(&data, &broken, "op-broken");
    std::fs::remove_file(broken.join("config.yaml.freedom-new")).unwrap();
    let mut core = spawn("serve", &data, &locks, &[]);
    let hello = core.hello();
    assert_eq!(
        hello["result"]["node_recovery"],
        json!({ "status": "corrupt", "node": "bee" })
    );
    // Reported again on the next start, until a write installs Bee.
    core.close_stdin();
    assert_eq!(core.exit_code(Duration::from_secs(5)), 0);
    let mut core = spawn("serve", &data, &locks, &[]);
    let hello = core.hello();
    assert_eq!(
        hello["result"]["node_recovery"],
        json!({ "status": "corrupt", "node": "bee" })
    );
}

#[test]
fn journals_a_writer_never_produces_are_set_aside_untouched() {
    let (root, data, locks) = dirs();
    std::fs::create_dir_all(&data).unwrap();
    let vault = data.join("identity-vault.json");
    std::fs::write(&vault, b"{}").unwrap();
    let elsewhere = root.path().join("elsewhere");
    std::fs::write(&elsewhere, b"other").unwrap();
    let digest: String = sha2::Sha256::digest(b"other")
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    let journal = json!({ "op_id": "x", "node": "bee", "root": data,
        "files": [{ "target": vault, "staged": elsewhere, "sha256": digest }] });
    std::fs::write(data.join("node-identity-journal.json"), journal.to_string()).unwrap();
    let mut core = spawn("serve", &data, &locks, &[]);
    let hello = core.hello();
    assert_eq!(
        hello["result"]["node_recovery"],
        json!({ "status": "corrupt" })
    );
    assert_eq!(std::fs::read(&vault).unwrap(), b"{}");
    assert_eq!(std::fs::read(&elsewhere).unwrap(), b"other");
    assert!(data.join("node-identity-journal.json.corrupt").exists());
}

#[test]
fn op_ids_are_single_use_and_oversized_configs_are_refused() {
    let (root, data, locks) = dirs();
    let mut core = unlocked(&data, &locks, &[]);
    let bee = root.path().join("bee");
    let params =
        json!({ "op_id": "op-1", "node": "bee", "data_dir": bee, "api_port": 1, "p2p_port": 2 });
    assert_eq!(
        core.call(3, "nodes.write_identity", params.clone())["result"]["status"],
        "installed"
    );
    let again = core.call(4, "nodes.write_identity", params);
    assert_eq!(again["error"]["code"], "invalid_argument", "{again}");
    assert_eq!(again["error"]["message"], "op_id already used");

    // A Radicle config larger than any node file: refused before staging.
    let home = root.path().join("radicle");
    std::fs::create_dir_all(&home).unwrap();
    let big = format!("{{\"pad\":\"{}\"}}", "x".repeat(1 << 20));
    std::fs::write(home.join("config.json"), &big).unwrap();
    let refused = core.call(
        5,
        "nodes.write_identity",
        json!({ "op_id": "op-2", "node": "radicle", "home": home, "alias": "me" }),
    );
    assert_eq!(refused["error"]["code"], "storage", "{refused}");
    assert_eq!(refused["error"]["data"]["kind"], "too_large");
    assert!(!home.join("keys").exists());
    assert_eq!(
        std::fs::read_to_string(home.join("config.json")).unwrap(),
        big
    );
}

#[test]
fn an_unfinishable_recovery_is_reported_and_blocks_new_writes() {
    let (root, data, locks) = dirs();
    let node = root.path().join("node");
    interrupted_write(&data, &node, "op-stuck");
    // The install can't rename over a directory.
    std::fs::remove_file(node.join("config.yaml")).unwrap();
    std::fs::create_dir_all(node.join("config.yaml").join("inside")).unwrap();

    let mut core = spawn("serve", &data, &locks, &[]);
    let hello = core.hello();
    assert_eq!(
        hello["result"]["node_recovery"],
        json!({ "status": "pending_recovery", "op_id": "op-stuck", "node": "bee" })
    );
    core.call(
        2,
        "vault.import",
        json!({ "password_b64": b64("testpass1"), "mnemonic_b64": b64(ABANDON) }),
    );
    // A new write first tries to finish the outstanding journal, and refuses
    // to replace it when that fails.
    let other = root.path().join("other");
    let refused = core.call(
        3,
        "nodes.write_identity",
        json!({ "op_id": "op-new", "node": "bee", "data_dir": other, "api_port": 1, "p2p_port": 2 }),
    );
    assert_eq!(refused["error"]["code"], "storage", "{refused}");
    assert!(!other.exists());
    let status = core.call_shell(4, "nodes.op_status", json!({ "op_id": "op-stuck" }));
    assert_eq!(status["result"]["status"], "pending_recovery");
    core.close_stdin();
    assert_eq!(core.exit_code(Duration::from_secs(5)), 0);

    // Once the obstacle is gone, the next start finishes it.
    std::fs::remove_dir_all(node.join("config.yaml")).unwrap();
    let mut core = spawn("serve", &data, &locks, &[]);
    assert_eq!(core.hello()["result"]["node_recovery"], Value::Null);
    assert_eq!(
        std::fs::read_to_string(node.join("config.yaml")).unwrap(),
        "new config"
    );
}
